from dreamer_ma import DreamerMA

PAST_ACTION = 0
PAST_CHANCE = 1
MODEL_NODE = 2

LOW_ACCURACY_THRESHOLD = 0.2
MISMATCH_THRESHOLD = 0.5

def custom_edge_style(parent: Node, child: Node):
    """
    Generate Graphviz DOT attributes for the edge based on the child node's data.
    """
    
    # Safely retrieve data from the child node
    child_data = child.data if child.data is not None else {}
    if not "type" in child_data:
        raise ValueError(f"Child data should contain a type field, but it does not. Got {child_data}")
    node_type = child_data["type"]
    if node_type == PAST_ACTION:
        if not "action" in child_data:
            raise ValueError(f"Child data for post action node should contain action field, but it does not. Got {child_data}")
        label = f"A: {child_data["action"]}, P: {float(child_data['prob']):.3f}"
    else:
        if not "prob" in child_data:
            raise ValueError(f"Child data for non-action node should contain prob field, but it does not. Got {child_data}")
        label = f"P: {float(child_data["prob"]):.3f}"
    attributes = {"label": label}
    # Convert the attributes dictionary to a DOT string format
    return ', '.join([f'{k}="{v}"' for k, v in attributes.items()])

def custom_node_style(node: Node):
    """
    Generate Graphviz DOT attributes for a node
    of tree generated by Dreamer evaluation
    """
    
    # Safely retrieve data
    data = node.data if node.data is not None else {}
    node_shapes = ("diamond", "ellipse", "box")
    if not "type" in data:
        raise ValueError(f"Node data should contain a type field, but it does not. Got {data}")
    node_type = data["type"]
    # Set default style
    attributes = {
        'shape': node_shapes[node_type],
        'style': 'filled',
        'fillcolor': 'lightblue',
    }
    label = node.name
    if node_type == MODEL_NODE:
        differences = data["differences"]
        category_names = ("O", "T", "R") if len(differences) == 3 else ("I1", "I2", "T", "R", "L")
        #if len(differences)
        max_diff_element = np.argmax(differences)
        max_diff = differences[max_diff_element]
        if max_diff >= MISMATCH_THRESHOLD:
            attributes['fillcolor'] = 'salmon'
            label = label + f"_{category_names[max_diff_element]}:{max_diff:.2f}"
        elif max_diff >= LOW_ACCURACY_THRESHOLD:
            attributes['fillcolor'] = 'yellow'
            label = label + f"_{category_names[max_diff_element]}:{max_diff:.2f}"
        else:
            attributes['fillcolor'] = 'lightgreen'
        
    attributes['fontname'] = 'Arial'
    attributes["label"] = label
    attributes['tooltip'] = f"ID: {node.name}" # Tooltip for interactive viewers

    # Convert the attributes dictionary to a DOT string format
    return ', '.join([f'{k}="{v}"' for k, v in attributes.items()])

