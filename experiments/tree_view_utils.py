def render_tree(root: Node, model: DreamerMA):
    game = model.game
    game_name = game.game_name()
    empty = ""
    game_params = game.params_dict()
    params_str = f'{empty.join(f"_{value}" for key, value in game_params.items())}'
    tree_save_dir = f"game_trees/{game_name}{params_str}/seed{model.init_seed}/"
    tree_save_dir = os.getcwd() + "/" +  tree_save_dir
    os.makedirs(tree_save_dir, exist_ok=True)

    output_filename = tree_save_dir + f"step_{model.learner_steps}.png"
    exporter = DotExporter(root,
                           nodeattrfunc=custom_node_style,
                           #nodenamefunc= custom_node_name,
                            edgeattrfunc=custom_edge_style)
    exporter.to_picture(output_filename)

    print(f"Graphviz DOT code has been saved and rendered to {output_filename}")